import { readFile, writeFile } from 'node:fs/promises';

// The modules have no dependencies. Each becomes a closure in one classic
// script, so index.html also works from a file:// URL, where browsers refuse
// to load ES modules.
const FILES = ['clay.js', 'mesh.js', 'render.js', 'app.js'];

export async function browserSource() {
  const parts = [];
  for (const file of FILES) {
    let src = await readFile(new URL(`../src/${file}`, import.meta.url), 'utf8');
    const names = [...src.matchAll(/^export (?:const|function|class) (\w+)/gm)].map(m => m[1]);
    src = src.replace(/^import \{([^}]+)\} from '\.\/(\w+)\.js';\s*$/gm, (_, list, mod) => `const {${list}} = modules.${mod};`);
    src = src.replace(/^export /gm, '');
    parts.push(`// src/${file}\nmodules.${file.replace('.js', '')} = (() => {\n${src}\nreturn { ${names.join(', ')} };\n})();`);
  }
  return parts.join('\n\n');
}

if (process.argv[1] && new URL(import.meta.url).pathname === process.argv[1]) {
  const source = await browserSource();
  await writeFile(new URL('../app.bundle.js', import.meta.url), `// Generated by npm run build. Edit src/ files.\n(() => {\n'use strict';\nconst modules = {};\n${source}\n})();\n`);
  console.log('Built app.bundle.js. Open index.html directly.');
}
